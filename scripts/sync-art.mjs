// Regenerates the only two inline SVG art pieces from the prototype:
// the nav brand mark and the footer scene. The prototype's 26 symbol sprite
// is not extracted; every other icon comes from a package.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prototypePath = resolve(root, '../van-sirisouk-concept-2/index.html');

const sourcePath = process.argv[2]
	? resolve(process.cwd(), process.argv[2])
	: prototypePath;

if (!existsSync(sourcePath)) {
	console.error(
		`Missing prototype: ${sourcePath}\nPass the index.html path: node scripts/sync-art.mjs ../van-sirisouk-concept-2/index.html`
	);
	process.exit(1);
}

const html = readFileSync(sourcePath, 'utf8');

function innerMarkup(className) {
	const pattern = new RegExp(
		`<svg[^>]*class="[^"]*\\b${className}\\b[^"]*"[^>]*>([\\s\\S]*?)</svg>`
	);
	const match = html.match(pattern);

	if (match === null) {
		throw new Error(`No svg.${className} in ${sourcePath}`);
	}

	return match[1];
}

function countRects(markup) {
	return (markup.match(/<rect\b/g) ?? []).length;
}

function inspect(label, markup, expectedRects) {
	if (/<svg\b|<symbol\b/i.test(markup)) {
		throw new Error(`${label}: inner markup contains an svg or symbol`);
	}

	if (/https?:\/\//i.test(markup)) {
		throw new Error(`${label}: inner markup contains a remote reference`);
	}

	const rects = countRects(markup);

	if (rects !== expectedRects) {
		throw new Error(
			`${label}: expected ${expectedRects} rects, found ${rects}`
		);
	}

	return rects;
}

function source(exportsName, markup) {
	return [
		'// Generated by scripts/sync-art.mjs from the prototype.',
		'// Do not edit by hand; run `node scripts/sync-art.mjs` instead.',
		'// biome-ignore format: generated art markup',
		`export const ${exportsName} = ${JSON.stringify(markup)};`,
		'',
	].join('\n');
}

const navMarkup = innerMarkup('brand__mark');
const footerMarkup = innerMarkup('foot__decor');

const navRects = inspect('brand__mark', navMarkup, 76);
const footerRects = inspect('foot__decor', footerMarkup, 187);

const iconsDir = join(root, 'components/icons');
mkdirSync(iconsDir, { recursive: true });

writeFileSync(
	join(iconsDir, 'nav-mark-markup.ts'),
	source('NAV_MARK_MARKUP', navMarkup)
);
writeFileSync(
	join(iconsDir, 'footer-markup.ts'),
	source('FOOTER_MARKUP', footerMarkup)
);

console.log(
	`brand__mark: ${navRects} rects -> components/icons/nav-mark-markup.ts`
);
console.log(
	`foot__decor: ${footerRects} rects -> components/icons/footer-markup.ts`
);
